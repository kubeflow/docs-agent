#!/usr/bin/env bash
# Promote a commit on main to production.
#
#   deploy/promote.sh [<commit>] [--open]
#
# Moves every `# prod-revision` line in deploy/argocd/apps/ to <commit> (default: the
# tip of main) on a new branch promote/<short sha>, and writes the PR description:
# the commits since the current prod revision and a section for the staging eval.
# With --open it also pushes the branch to your fork and opens the PR.
# After the PR merges, Argo CD syncs production to that commit; revert the PR to roll back.
#
# Remotes: UPSTREAM (default origin) is kubeflow/docs-agent, FORK (default fork) is yours.
set -euo pipefail

UPSTREAM=${UPSTREAM:-origin}
FORK=${FORK:-fork}
REPO=kubeflow/docs-agent
APPS=(deploy/argocd/apps/docs-agent.yaml deploy/argocd/apps/gateway-guardrails.yaml)
IMAGES=(mcp-kubeflow-docs kubeflow-session-issuer)

die() { echo "promote: $*" >&2; exit 1; }

open=false target=""
for arg in "$@"; do
  case "$arg" in
    --open) open=true ;;
    -h|--help) sed -n '2,13p' "$0"; exit 0 ;;
    *) target=$arg ;;
  esac
done

cd "$(git rev-parse --show-toplevel)"
[ -z "$(git status --porcelain --untracked-files=no)" ] || die "commit or stash your changes first"
git fetch -q "$UPSTREAM" main

new=$(git rev-parse --verify "${target:-$UPSTREAM/main}^{commit}") || die "unknown commit: $target"
git merge-base --is-ancestor "$new" "$UPSTREAM/main" || die "$new is not on $UPSTREAM/main"
short=${new:0:7}

old=$(git show "$UPSTREAM/main:${APPS[0]}" | sed -n 's/.*targetRevision: \([0-9a-f]\{40\}\) *# prod-revision.*/\1/p' | head -1)
[ -n "$old" ] || die "no prod-revision found in ${APPS[0]}"
[ "$old" != "$new" ] || die "$short is already in production"
git merge-base --is-ancestor "$old" "$new" || die "$short is older than production (${old:0:7}); to roll back, revert the promotion PR"

# CI pushes both images on every main build, tagged with the short SHA.
for image in "${IMAGES[@]}"; do
  token=$(curl -fsS "https://ghcr.io/token?scope=repository:kubeflow/$image:pull" | sed -n 's/.*"token":"\([^"]*\)".*/\1/p')
  code=$(curl -s -o /dev/null -w '%{http_code}' -H "Authorization: Bearer $token" \
    -H 'Accept: application/vnd.oci.image.index.v1+json, application/vnd.docker.distribution.manifest.v2+json' \
    "https://ghcr.io/v2/kubeflow/$image/manifests/$short")
  [ "$code" = 200 ] || die "ghcr.io/kubeflow/$image:$short not found (HTTP $code); wait for the main build"
done

branch=promote/$short
git switch -q -c "$branch" "$UPSTREAM/main"
for f in "${APPS[@]}"; do
  sed -i.bak "s/targetRevision: [0-9a-f]\{40\}\( *# prod-revision\)/targetRevision: $new\1/" "$f" && rm -f "$f.bak"
done
git commit -q -s -m "chore(release): promote $short to prod" -- "${APPS[@]}"

body=$(mktemp)
{
  echo "Promotes production from \`${old:0:7}\` to \`$short\`."
  echo
  echo "Generated by \`deploy/promote.sh\`. Only the \`# prod-revision\` lines change. After merge, Argo CD"
  echo "syncs \`docs-agent\` and \`gateway-guardrails\` to this commit, with images"
  echo "\`ghcr.io/kubeflow/mcp-kubeflow-docs:$short\` and \`ghcr.io/kubeflow/kubeflow-session-issuer:$short\`."
  echo
  echo "### Changes since the current production"
  echo
  git log --no-merges --reverse --format='- %s (%h)' "$old..$new"
  echo
  echo "### Staging eval for \`$short\`"
  echo
  echo "Langfuse project flo-eval, Experiments, run named \`$short …\`."
  echo
  echo "| Routing | Grounded | Errors |"
  echo "|---|---|---|"
  echo "|  |  |  |"
  echo
  echo "### Rollback"
  echo
  echo "Revert this PR. Argo CD syncs production back to \`${old:0:7}\`."
} > "$body"

if $open; then
  git push -q -u "$FORK" "$branch"
  owner=$(git remote get-url "$FORK" | sed -E 's#.*[:/]([^/]+)/[^/]+(\.git)?$#\1#')
  gh pr create --repo "$REPO" --base main --head "$owner:$branch" \
    --title "chore(release): promote $short to prod" --body-file "$body"
else
  echo "Branch $branch is ready. Review it, then open the PR with:"
  echo "  git push -u $FORK $branch"
  echo "  gh pr create --repo $REPO --base main --head <your-user>:$branch --title \"chore(release): promote $short to prod\" --body-file $body"
fi
